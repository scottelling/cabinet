import fs from "node:fs/promises";
import path from "node:path";

const projectRoot = process.cwd();
const apiRoot = path.join(projectRoot, "src", "app", "api");
const outputPath = path.join(
  projectRoot,
  "src",
  "lib",
  "cloud",
  "generated-route-manifest.ts"
);

async function findRoutes(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await findRoutes(absolute)));
    } else if (entry.isFile() && entry.name === "route.ts") {
      files.push(absolute);
    }
  }
  return files;
}

function escapeRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function routeInfo(file, index) {
  const relativeDirectory = path.relative(apiRoot, path.dirname(file)).split(path.sep).join("/");
  const segments = relativeDirectory.split("/").filter(Boolean);
  const params = [];
  let staticSegments = 0;
  let hasCatchAll = false;
  const regexParts = segments.map((segment) => {
    const optionalCatchAll = /^\[\[\.\.\.([^\]]+)\]\]$/.exec(segment);
    if (optionalCatchAll) {
      params.push({ name: optionalCatchAll[1], catchAll: true, optional: true });
      hasCatchAll = true;
      return "(.*)";
    }
    const catchAll = /^\[\.\.\.([^\]]+)\]$/.exec(segment);
    if (catchAll) {
      params.push({ name: catchAll[1], catchAll: true, optional: false });
      hasCatchAll = true;
      return "(.+)";
    }
    const dynamic = /^\[([^\]]+)\]$/.exec(segment);
    if (dynamic) {
      params.push({ name: dynamic[1], catchAll: false, optional: false });
      return "([^/]+)";
    }
    staticSegments += 1;
    return escapeRegex(segment);
  });

  return {
    importPath: `@/app/api/${relativeDirectory}/route`,
    pathname: `/api/${relativeDirectory}`.replace(/\/$/, ""),
    regex: `^/api/${regexParts.join("/")}/?$`,
    params,
    staticSegments,
    hasCatchAll,
    segmentCount: segments.length,
  };
}

const files = (await findRoutes(apiRoot))
  .filter((file) => !file.includes(`${path.sep}cloud-runtime${path.sep}`))
  .sort();

const routes = files
  .map(routeInfo)
  .sort((left, right) => {
    if (left.staticSegments !== right.staticSegments) {
      return right.staticSegments - left.staticSegments;
    }
    if (left.hasCatchAll !== right.hasCatchAll) {
      return left.hasCatchAll ? 1 : -1;
    }
    return right.segmentCount - left.segmentCount;
  });

const entries = routes
  .map(
    (route) => `  {
    pathname: ${JSON.stringify(route.pathname)},
    pattern: new RegExp(${JSON.stringify(route.regex)}),
    params: ${JSON.stringify(route.params)},
    load: async () => (await import(${JSON.stringify(route.importPath)})) as unknown as CloudRouteModule,
  },`
  )
  .join("\n");

const source = `/* eslint-disable */
// Generated by scripts/generate-cloud-route-manifest.mjs. Do not edit by hand.
import type { NextRequest } from "next/server";

export type CloudRouteMethod = "GET" | "POST" | "PUT" | "PATCH" | "DELETE" | "HEAD" | "OPTIONS";
export type CloudRouteHandler = (
  request: NextRequest,
  context: { params: Promise<Record<string, string | string[]>> }
) => Response | Promise<Response>;
export type CloudRouteModule = Partial<Record<CloudRouteMethod, CloudRouteHandler>>;

interface CloudRouteEntry {
  pathname: string;
  pattern: RegExp;
  params: Array<{ name: string; catchAll: boolean; optional: boolean }>;
  load: () => Promise<CloudRouteModule>;
}

const routes: CloudRouteEntry[] = [
${entries}
];

export function matchCloudRoute(pathname: string): {
  pathname: string;
  load: () => Promise<CloudRouteModule>;
  params: Record<string, string | string[]>;
} | null {
  for (const route of routes) {
    const match = route.pattern.exec(pathname);
    if (!match) continue;
    const params: Record<string, string | string[]> = {};
    route.params.forEach((parameter, index) => {
      const raw = match[index + 1] || "";
      if (parameter.catchAll) {
        params[parameter.name] = raw
          ? raw.split("/").filter(Boolean).map((part) => decodeURIComponent(part))
          : [];
      } else if (raw || !parameter.optional) {
        params[parameter.name] = decodeURIComponent(raw);
      }
    });
    return { pathname: route.pathname, load: route.load, params };
  }
  return null;
}
`;

await fs.mkdir(path.dirname(outputPath), { recursive: true });
await fs.writeFile(outputPath, source, "utf8");
console.log(`[cabinet] generated cloud route manifest (${routes.length} routes)`);
